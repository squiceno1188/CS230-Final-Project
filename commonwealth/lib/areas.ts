export function getArea(slug: string) {
  return AREAS.find((area) => area.slug === slug);
}

export function areaNames(slugs: string[]) {
  return slugs.map((slug) => getArea(slug)?.name ?? slug).filter(Boolean);
}

export function groupId(group: string) {
  return group.toLowerCase().replace(/[^a-z]+/g, "-").replace(/(^-|-$)/g, "");
}
